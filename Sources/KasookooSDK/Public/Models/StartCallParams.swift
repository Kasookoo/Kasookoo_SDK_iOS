import Foundation

/// Parameters for starting a call.
///
/// Matches the `/api/v1/webrtc/get-call-tokens` backend contract.
///
/// ## Example
/// ```swift
/// try await sdk.call.start(
///     params: StartCallParams(
///         roomName: "support-room-123",
///         caller: caller,
///         callee: agent,
///         isPushNotification: true,
///         isCallRecording: false
///     )
/// )
/// ```
public struct StartCallParams: Sendable, Hashable {
    
    // MARK: - Properties
    
    /// The unique room name for this call. Generated by your app or backend.
    public let roomName: String
    
    /// The caller's identity.
    public let caller: Participant
    
    /// The callee's identity.
    public let callee: Participant
    
    /// Whether to send push notifications to the callee. Defaults to `true`.
    public let isPushNotification: Bool
    
    /// Whether to record the call. Defaults to `false`.
    public let isCallRecording: Bool
    
    // MARK: - Init
    
    /// Creates new call parameters.
    ///
    /// - Parameters:
    ///   - roomName: The unique room name.
    ///   - caller: The caller's identity.
    ///   - callee: The callee's identity.
    ///   - isPushNotification: Send push to callee. Defaults to `true`.
    ///   - isCallRecording: Record the call. Defaults to `false`.
    public init(
        roomName: String,
        caller: Participant,
        callee: Participant,
        isPushNotification: Bool = true,
        isCallRecording: Bool = false
    ) {
        self.roomName = roomName
        self.caller = caller
        self.callee = callee
        self.isPushNotification = isPushNotification
        self.isCallRecording = isCallRecording
    }
    
    // MARK: - Validation
    
    /// Validates the parameters before sending to the backend.
    ///
    /// - Throws: `KasookooError.configInvalid` if validation fails.
    public func validate() throws {
        var errors: [String: String] = [:]
        
        if roomName.trimmingCharacters(in: .whitespaces).isEmpty {
            errors["roomName"] = "roomName cannot be empty"
        }
        
        do { try caller.validate() } catch let e as KasookooError {
            errors["caller"] = e.message
        }
        
        do { try callee.validate() } catch let e as KasookooError {
            errors["callee"] = e.message
        }
        
        if caller.email == callee.email {
            errors["callee"] = "caller and callee cannot have the same email"
        }
        
        if !errors.isEmpty {
            throw KasookooError.configInvalid(
                "Invalid call parameters.",
                details: errors
            )
        }
    }
}
